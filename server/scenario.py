"""Authored training graph. Scores/times are prototype settings, not railway regulations."""

from pydantic import BaseModel, model_validator


class Choice(BaseModel):
    id: str
    label: str
    next: str
    feedback: str
    quality: int = 0
    trust: int = 0
    competency: str | None = None
    flag: str | None = None
    serious: bool = False


class Node(BaseModel):
    id: str
    phase: str
    title: str
    text: str
    target: str
    location: str
    source: str
    choices: list[Choice]
    seconds: int | None = None
    timeout: str | None = None
    wait: int = 0


class Scenario(BaseModel):
    version: str
    start: str
    nodes: dict[str, Node]

    @model_validator(mode="after")
    def valid_graph(self):
        assert self.start in self.nodes
        for key, node in self.nodes.items():
            assert node.id == key
            assert len({c.id for c in node.choices}) == len(node.choices)
            for choice in node.choices:
                assert choice.next in self.nodes or choice.next in ("complete", "stopped")
            if node.seconds:
                assert node.timeout in {c.id for c in node.choices}
        return self


